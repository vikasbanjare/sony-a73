"""DaVinci Resolve DCTL export.

Two flavours:
- ``matrix_dctl``: the 3x3 CCM as pure maths. Put it between two Color
  Space Transform nodes (camera log -> linear, then linear -> output).
- ``lut_dctl``: wraps a generated ``.cube`` (which already includes the
  curves, CCM and residual correction) so it can be versioned as a DCTL.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

_HEADER = "// Generated by a7iii-enhanced-suite. Do not edit by hand.\n"


def matrix_dctl(matrix: np.ndarray, name: str = "a7iii_match") -> str:
    m = np.asarray(matrix, dtype=np.float64)
    if m.shape != (3, 3):
        raise ValueError("matrix DCTL needs a 3x3 matrix (degree=1 CCM)")
    rows = [
        f"    const float {c} = {m[i, 0]:.8f}f * p_R + {m[i, 1]:.8f}f * p_G + {m[i, 2]:.8f}f * p_B;"
        for i, c in enumerate("rgb")
    ]
    return (
        _HEADER
        + f"// {name}: 3x3 colour-correction matrix. Expects scene-linear input.\n"
        + "__DEVICE__ float3 transform(int p_Width, int p_Height, int p_X, int p_Y, float p_R, float p_G, float p_B)\n"
        + "{\n"
        + "\n".join(rows)
        + "\n    return make_float3(r, g, b);\n}\n"
    )


def lut_dctl(cube_path: str | Path, name: str = "a7iii_match") -> str:
    cube = Path(cube_path).name
    return (
        _HEADER
        + f"// {name}: keep {cube} in the same folder as this file.\n"
        + f'DEFINE_LUT(MatchLUT, "{cube}")\n'
        + "__DEVICE__ float3 transform(int p_Width, int p_Height, int p_X, int p_Y, float p_R, float p_G, float p_B)\n"
        + "{\n"
        + "    return APPLY_LUT(p_R, p_G, p_B, MatchLUT);\n}\n"
    )
